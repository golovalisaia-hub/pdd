test('приложение и PWA используют один путь и открывают экраны без сети', async ({ page, context, baseURL }) => {
  const appUrl = new URL('./', baseURL)
  const bankRequest = page.waitForRequest(request => new URL(request.url()).pathname.endsWith('/bank/abm.json'))
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'PDD', exact: true })).toBeVisible()
  expect((await bankRequest).url()).toBe(new URL('bank/abm.json', appUrl).href)
  await expect(page.locator('link[rel="icon"]')).toHaveAttribute('href', appUrl.pathname + 'pdd-icon.svg')
  await expect(page.locator('link[rel="apple-touch-icon"]')).toHaveAttribute('href', appUrl.pathname + 'pdd-192.png')
  await expect(page.locator('link[rel="manifest"]')).toHaveAttribute('href', appUrl.pathname + 'manifest.webmanifest')
  const manifestUrl = new URL('manifest.webmanifest', appUrl)
  const manifestResponse = await page.request.get(manifestUrl.href)
  expect(manifestResponse.ok()).toBe(true)
  const manifest = await manifestResponse.json()
  expect(manifest).toMatchObject({ id: appUrl.pathname, start_url: appUrl.pathname, scope: appUrl.pathname })
  const icons = ['pdd-192.png', 'pdd-512.png', 'pdd-maskable.png'].map(name => new URL(name, appUrl).href)
  expect(manifest.icons.map(({ src }: { src: string }) => new URL(src, manifestUrl).href)).toEqual(icons)
  for (const icon of icons) {
    const response = await page.request.get(icon)
    expect(response.ok()).toBe(true)
    expect(response.headers()['content-type']).toContain('image/png')
  }
  await expect.poll(() => page.evaluate(() => navigator.serviceWorker.controller?.scriptURL), { timeout: 15_000 }).toBe(new URL('sw.js', appUrl).href)
  expect(await page.evaluate(async () => (await navigator.serviceWorker.ready).scope)).toBe(appUrl.href)
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'PDD', exact: true })).toBeVisible()
  for (const selector of ['.hero-image', '.brand img']) {
    await expect.poll(() => page.locator(selector).first().evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  }
  await page.goto('./#/spravochnik')
  await expect(page.getByRole('heading', { name: 'Справочник ПДД', exact: true })).toBeVisible()
  await page.goto('./#/perekrestki')
  await expect(page.getByRole('heading', { name: 'Перекрёстки', exact: true })).toBeVisible()
  await page.goto('./#/bilety?komplekt=uchebny')
  await page.getByRole('button', { name: 'Учебный билет 1', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Иллюстрация к вопросу' })).toBeVisible()
  await expect.poll(() => page.getByRole('img', { name: 'Иллюстрация к вопросу' }).evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
})

test('завершает билет, находит ошибки и открывает повторение', async ({ page }) => {
  await page.goto('./#/bilety?komplekt=uchebny')
  await page.getByRole('button', { name: 'Учебный билет 1', exact: true }).click()
  const ticket = practiceBank.questions.filter(question => question.ticket === 1)
  for (const [i, question] of ticket.entries()) {
    await expect(page.getByText('Вопрос ' + (i + 1) + ' из 20', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: question.options[i === 0 ? 1 : question.correct], exact: true }).click()
    await expect(page.getByRole('heading', { name: i === 0 ? 'Есть ошибка' : 'Верно!', exact: true })).toBeVisible()
    await page.getByRole('button', { name: i === 19 ? 'К результату' : 'Далее', exact: true }).click()
  }
  await expect(page.getByRole('heading', { name: 'Занятие завершено' })).toBeVisible()
  await expect(page.getByText('95%', { exact: true })).toBeVisible()
  await page.goto('./#/oshibki?komplekt=uchebny')
  await expect(page.getByText(ticket[0].text, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Повторить ошибки', exact: true }).click()
  await expect(page.getByText('Вопрос 1 из 1', { exact: true })).toBeVisible()
})

