async function capture(page: Page, info: TestInfo, name: string, animation = '.screen') {
  await expect.poll(() => page.locator(animation).evaluate(element => getComputedStyle(element).opacity)).toBe('1')
  await page.evaluate(() => document.fonts.ready.then(() => undefined))
  await page.screenshot({ path: info.outputPath(name), fullPage: true, animations: 'disabled' })
}

